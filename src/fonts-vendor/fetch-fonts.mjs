// Self-host the app's font (Nunito) instead of loading it from Google Fonts at
// runtime. Downloads EXACTLY what Google Fonts serves for the stylesheet the app
// used to link (same files, same @font-face rules, same unicode ranges), stores
// the files in www/fonts/, and writes www/css/fonts.css pointing at them, plus
// www/fonts/SOURCE.md (origin + SHA-256 of each file) and the font's licence.
// The app then never contacts Google Fonts. Re-run only to update the font:
//
//   node src/fonts-vendor/fetch-fonts.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const CSS_URL = "https://fonts.googleapis.com/css2?family=Nunito:wght@400;600;700;800&display=swap";
const LICENSE_URL = "https://raw.githubusercontent.com/google/fonts/main/ofl/nunito/OFL.txt";
// Google serves woff2 + per-script subsets to modern browsers; ask like one.
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36";

async function get(url) {
    const r = await fetch(url, { headers: { "User-Agent": UA } });
    if (!r.ok) throw new Error(`${r.status} for ${url}`);
    return Buffer.from(await r.arrayBuffer());
}

const css = (await get(CSS_URL)).toString("utf8");
mkdirSync(resolve(ROOT, "www/fonts"), { recursive: true });

// Each "/* subset */ @font-face {...}" block; files are shared between weights.
const files = new Map(); // remote url -> local file name
let out = css.replace(/\/\* ([a-z-]+) \*\/\s*@font-face \{([\s\S]*?)\}/g, (block, subset, body) => {
    const url = /url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/.exec(body)[1];
    if (!files.has(url)) files.set(url, `nunito-${subset}.woff2`);
    return block.replace(url, `../fonts/${files.get(url)}`);
});
if (/fonts\.gstatic\.com|fonts\.googleapis\.com/.test(out)) throw new Error("unexpected remote URL left in CSS");

const lines = [];
for (const [url, name] of files) {
    const buf = await get(url);
    writeFileSync(resolve(ROOT, "www/fonts", name), buf);
    lines.push(`| \`${name}\` | ${buf.length} | \`${createHash("sha256").update(buf).digest("hex")}\` | ${url} |`);
}
out = `/* Nunito, self-hosted (generated by src/fonts-vendor/fetch-fonts.mjs - do not
   edit). Same files and @font-face rules Google Fonts serves for
   ${CSS_URL}
   Licence: SIL Open Font License 1.1 (www/fonts/OFL.txt). */
` + out;
writeFileSync(resolve(ROOT, "www/css/fonts.css"), out);
writeFileSync(resolve(ROOT, "www/fonts/OFL.txt"), await get(LICENSE_URL));
writeFileSync(resolve(ROOT, "www/fonts/SOURCE.md"),
`# Self-hosted fonts

Nunito (SIL Open Font License 1.1, see \`OFL.txt\`), downloaded from Google Fonts by
\`src/fonts-vendor/fetch-fonts.mjs\` on ${new Date().toISOString().slice(0, 10)} - exactly the files Google
Fonts served for \`${CSS_URL}\`. The tests check these fingerprints.

| File | Bytes | SHA-256 | Downloaded from |
|---|---|---|---|
${lines.join("\n")}
`);
console.log(`Wrote www/css/fonts.css and ${files.size} font files to www/fonts/`);
